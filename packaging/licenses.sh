#!/usr/bin/env bash
# Write THIRD_PARTY_LICENSES from each module in `go list -m all`.
set -euo pipefail
cd "$(dirname "$0")/.."
out="${1:-THIRD_PARTY_LICENSES}"
: >"$out"
echo "gio-ide third-party licenses" >>"$out"
echo "Generated by packaging/licenses.sh" >>"$out"
go list -m -json all | jq -r 'select(.Dir != null) | [.Path, (.Version // ""), .Dir] | @tsv' |
	while IFS=$'\t' read -r path ver dir; do
		for name in LICENSE LICENSE.md LICENSE.txt COPYING COPYING.md NOTICE NOTICE.md PATENTS; do
			if [[ -f "$dir/$name" ]]; then
				printf '\n===== %s %s %s =====\n' "$path" "$ver" "$name" >>"$out"
				cat "$dir/$name" >>"$out"
			fi
		done
	done
append_file() {
	local label="$1" path="$2"
	if [[ -f "$path" ]]; then
		printf '\n===== %s =====\n' "$label" >>"$out"
		cat "$path" >>"$out"
	fi
}

append_file "fork golang.org/x/tools LICENSE" internal/gopls/LICENSE
append_file "fork golang.org/x/tools PATENTS" internal/gopls/PATENTS
append_file "fork golang.org/x/tools NOTICE.md" internal/gopls/NOTICE.md
append_file "embedded gofumpt v0.12.0 LICENSE" internal/thirdparty/gofumpt/LICENSE
append_file "embedded gofumpt v0.12.0 LICENSE.google" internal/thirdparty/gofumpt/LICENSE.google
append_file "embedded goimports golang.org/x/tools v0.50.0 LICENSE" internal/thirdparty/goimports/LICENSE
echo "wrote $out"
