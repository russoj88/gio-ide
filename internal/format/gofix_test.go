func TestApplyUnified(t *testing.T) {
	tests := []struct {
		name string
		src  string
		diff string
		want string
	}{
		{
			name: "middle",
			src:  "a\nb\nc\n",
			diff: "--- f (old)\n+++ f (new)\n@@ -1,3 +1,3 @@\n a\n-b\n+B\n c\n",
			want: "a\nB\nc\n",
		},
		{
			name: "later hunk",
			src:  "a\nb\nc\nd\n",
			diff: "--- f (old)\n+++ f (new)\n@@ -3,2 +3,2 @@\n c\n-d\n+D\n",
			want: "a\nb\nc\nD\n",
		},
		{
			name: "no newline",
			src:  "a\nb",
			diff: "--- f (old)\n+++ f (new)\n@@ -1,2 +1,2 @@\n a\n-b\n\\ No newline at end of file\n+B\n\\ No newline at end of file\n",
			want: "a\nB",
		},
		{
			name: "two hunks",
			src:  "a\nb\nc\nd\ne\n",
			diff: "--- f (old)\n+++ f (new)\n@@ -1,2 +1,2 @@\n a\n-b\n+B\n@@ -4,2 +4,2 @@\n d\n-e\n+E\n",
			want: "a\nB\nc\nd\nE\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := applyUnified(tt.src, tt.diff)
			if err != nil {
				t.Fatal(err)
			}
			if got != tt.want {
				t.Fatalf("got %q want %q", got, tt.want)
			}
		})
	}
}

func TestGofixRejectsEmptyPathAndSkipsGenerated(t *testing.T) {
	if _, err := Gofix(context.Background(), "", []byte("package p\n")); err == nil {
		t.Fatal("empty path returned no error")
	}
	src := []byte("// Code generated by test. DO NOT EDIT.\n\npackage p\n\nfunc F(a, b int) int {\n\tx := a\n\tif a > b {\n\t\tx = b\n\t}\n\treturn x\n}\n")
	got, err := Gofix(context.Background(), "p.go", src)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(src) {
		t.Fatalf("generated file changed:\n%s", got)
	}
}

func TestGofixModernizesBuffer(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Fatal("go is not on PATH")
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/x\n\ngo 1.27.2\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	disk := []byte("package p\n\nfunc F() {}\n")
	file := filepath.Join(dir, "p.go")
	if err := os.WriteFile(file, disk, 0o644); err != nil {
		t.Fatal(err)
	}
	sibling := []byte("package p\n\nfunc G(v interface{}) interface{} { return v }\n")
	sib := filepath.Join(dir, "b.go")
	if err := os.WriteFile(sib, sibling, 0o644); err != nil {
		t.Fatal(err)
	}
	src := []byte(`package p

import "sync"

func F(a, b int) int {
	x := a
	if a > b {
		x = b
	}
	return x
}

func H(wg *sync.WaitGroup) {
	wg.Add(1)
	go func() {
		defer wg.Done()
	}()
}

func I(v interface{}) interface{} { return v }
`)
	got, err := Gofix(context.Background(), file, src)
	if err != nil {
		t.Fatal(err)
	}
	text := string(got)
	for _, want := range []string{"min(a, b)", "wg.Go(", "v any"} {
		if !strings.Contains(text, want) {
			t.Fatalf("missing %q:\n%s", want, text)
		}
	}
	for _, gone := range []string{"if a > b", "wg.Add(", "interface{}"} {
		if strings.Contains(text, gone) {
			t.Fatalf("still has %q:\n%s", gone, text)
		}
	}
	onDisk, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if string(onDisk) != string(disk) {
		t.Fatalf("p.go on disk changed:\n%s", onDisk)
	}
	onSib, err := os.ReadFile(sib)
	if err != nil {
		t.Fatal(err)
	}
	if string(onSib) != string(sibling) {
		t.Fatalf("sibling changed:\n%s", onSib)
	}

	plain := []byte("package p\n\nfunc F( a int) {}\n")
	again, err := Gofix(context.Background(), file, plain)
	if err != nil {
		t.Fatal(err)
	}
	if string(again) != string(plain) {
		t.Fatalf("unchanged buffer was rewritten:\n%s", again)
	}
}
